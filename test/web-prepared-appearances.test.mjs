  const boxes=await figures.evaluateAll(els=>els.map(el=>({x:el.getBoundingClientRect().x,y:el.getBoundingClientRect().y,height:el.getBoundingClientRect().height})));
  assert.ok(boxes.every(box=>Math.abs(box.y-boxes[0].y)<1 && box.height<520));
