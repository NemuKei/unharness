  assert.equal(await characters.getByRole('button',{name:'白銀',exact:true}).getAttribute('aria-pressed'),'false');
  await section.locator('figure[aria-label="比較プレビュー：琥珀"] .pixi-host[data-artwork-id="'+examples.amber+'"]').waitFor({state:'visible'});
  assert.equal(await section.getByText('描画を準備中…').count(),0);
