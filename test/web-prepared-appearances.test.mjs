  await page.emulateMedia({reducedMotion:'no-preference'});await page.goto('https://unharness.deltahelmlab.com/');
  const section=page.locator('.original-example'),stages=section.locator('.pixi-host');
  const examples=Object.fromEntries(await Promise.all(['silver','amber'].map(async id=>[id,JSON.parse(await readFile(new URL('../assets/appearance-examples/'+id+'-v2/artwork.json',import.meta.url),'utf8')).id])));
  await section.scrollIntoViewIfNeeded();await page.waitForFunction(()=>document.querySelectorAll('.original-example .pixi-host[data-cel="24"]').length===3);
